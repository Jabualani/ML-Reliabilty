"""
Meta-learning for StatCore / ReliableML.

Supported ``meta_variant`` styles:

1. performance_aware - weight base models by out-of-fold (OOF) log-loss.
2. metrics_based     - learn from metrics generated by the base models (confidence, entropy,
                       margin, inter-model agreement, OOF-F1-scaled probabilities).
3. oof_stacking      - classical OOF probability stacking with a logistic meta-model.
4. statistical_meta  - LDA + cluster-posterior + logistic meta-classifier, averaged.
5. calibrated_stack  - OOF stacking followed by temperature calibration learned on
                       nested out-of-fold meta predictions.

Every meta-model is trained on OOF predictions only (each base model sees a sample only
through folds that exclude it), so the meta level is leakage-free. The base models used at
prediction time are refit on all the data.
"""

from __future__ import annotations

import copy
from typing import Any, Sequence, Tuple

import numpy as np

from .._common import check_fitted, check_variant, check_X, check_Xy, golden_min, softmax, stratified_folds
from ..evaluation.metrics import classification_metrics
from ..kmeans.kmeans import KMeans
from ..lda.lda import LDA
from ..linear.linear import LogisticRegression

VARIANTS = ("performance_aware", "metrics_based", "oof_stacking", "statistical_meta", "calibrated_stack")


def _aligned_proba(est, X, classes, train_classes):
    """Class-probability matrix aligned to ``classes`` (one-hot of predict if no predict_proba)."""
    own = np.asarray(getattr(est, "classes_", train_classes))
    if hasattr(est, "predict_proba"):
        P = np.asarray(est.predict_proba(X), dtype=float)
    else:
        pred = np.asarray(est.predict(X))
        P = (pred[:, None] == own[None, :]).astype(float)
    out = np.zeros((len(X), len(classes)))
    pos = np.searchsorted(classes, own)
    out[:, pos] = P
    return out


def _entropy(P):
    return -np.sum(P * np.log(np.clip(P, 1e-12, None)), axis=1)


class MetaLearner:
    """Leakage-free meta-learner over a list of ``(name, estimator)`` classifiers.

    Parameters
    ----------
    base_estimators : sequence of (name, estimator); estimators need fit/predict and
        optionally predict_proba (StatCore models or sklearn-like objects). They are cloned.
    meta_variant : one of ``VARIANTS`` (see module docstring).
    n_folds : stratified folds used to build out-of-fold predictions.
    temperature : softness of the performance-aware weighting (smaller = closer to best-model
        selection).
    random_state : seed for fold assignment and meta-models.
    """

    def __init__(self, base_estimators: Sequence[Tuple[str, Any]], meta_variant="oof_stacking",
                 n_folds=5, temperature=0.1, random_state=42):
        check_variant(meta_variant, VARIANTS, "meta")
        ests = list(base_estimators)
        if not ests:
            raise ValueError("base_estimators must not be empty")
        names = []
        for item in ests:
            if not (isinstance(item, (tuple, list)) and len(item) == 2):
                raise ValueError("base_estimators must be (name, estimator) pairs")
            if not (hasattr(item[1], "fit") and hasattr(item[1], "predict")):
                raise ValueError(f"estimator {item[0]!r} needs fit and predict")
            names.append(item[0])
        if len(set(names)) != len(names):
            raise ValueError("base estimator names must be unique")
        if not isinstance(n_folds, (int, np.integer)) or n_folds < 2:
            raise ValueError("n_folds must be an integer >= 2")
        if temperature <= 0:
            raise ValueError("temperature must be positive")
        self.base_estimators = ests
        self.meta_variant = meta_variant
        self.n_folds = int(n_folds)
        self.temperature = temperature
        self.random_state = random_state
        self.is_fitted_ = False

    # ------------------------------------------------------------ features
    def _meta_features(self, Ps):
        """Meta-feature matrix from the list of per-model probability matrices."""
        v = self.meta_variant
        if v in ("oof_stacking", "calibrated_stack"):
            return np.hstack(Ps)
        if v == "statistical_meta":
            return np.hstack([np.log(np.clip(P, 1e-3, 1.0)) for P in Ps])
        # metrics_based
        mean = np.mean(Ps, axis=0)
        consensus = mean.argmax(1)
        cols = [P * self.model_metrics_[name]["f1_macro"] for (name, _), P in zip(self.base_estimators, Ps)]
        for P in Ps:
            Pr = np.sort(P, axis=1)
            margin = Pr[:, -1] - Pr[:, -2] if P.shape[1] > 1 else Pr[:, -1]
            cols.append(np.column_stack([Pr[:, -1], _entropy(P), margin]))
        agree = np.mean([P.argmax(1) == consensus for P in Ps], axis=0)
        cols.append(np.column_stack([agree, _entropy(mean)]))
        return np.hstack(cols)

    def _new_logistic(self):
        return LogisticRegression(alpha=1e-2, random_state=self.random_state)

    # ----------------------------------------------------------------- fit
    def fit(self, X, y):
        X, y = check_Xy(X, y, min_samples=max(4, self.n_folds))
        n = len(X)
        if self.n_folds > n:
            raise ValueError("n_folds cannot exceed the number of samples")
        self.classes_ = np.unique(y)
        C = len(self.classes_)
        if C < 2:
            raise ValueError("MetaLearner needs at least two classes")
        self.n_features_in_ = X.shape[1]
        M = len(self.base_estimators)
        folds = stratified_folds(y, self.n_folds, self.random_state)
        oof = np.zeros((M, n, C))
        for f in range(self.n_folds):
            tr, va = folds != f, folds == f
            if not va.any() or len(np.unique(y[tr])) < 2:
                raise ValueError("a training fold contains fewer than two classes; lower n_folds")
            tc = np.unique(y[tr])
            for m, (_, est) in enumerate(self.base_estimators):
                e = copy.deepcopy(est).fit(X[tr], y[tr])
                oof[m, va] = _aligned_proba(e, X[va], self.classes_, tc)
        self.oof_proba_ = oof

        self.model_metrics_, self.oof_log_loss_ = {}, {}
        for m, (name, _) in enumerate(self.base_estimators):
            self.model_metrics_[name] = classification_metrics(
                y, self.classes_[oof[m].argmax(1)], oof[m], classes=self.classes_)
            self.oof_log_loss_[name] = self.model_metrics_[name]["log_loss"]
        self.performance_scores_ = {k: v["accuracy"] for k, v in self.model_metrics_.items()}

        self.fitted_base_ = [(name, copy.deepcopy(est).fit(X, y)) for name, est in self.base_estimators]
        self._full_classes = self.classes_

        Ps = list(oof)
        v = self.meta_variant
        self.meta_model_ = None
        self.temperature_ = 1.0
        if v == "performance_aware":
            ll = np.array([self.oof_log_loss_[name] for name, _ in self.base_estimators])
            self.weights_ = softmax(-(ll - ll.min())[None, :] / self.temperature)[0]
            self.best_estimator_ = self.base_estimators[int(ll.argmin())][0]
        elif v in ("oof_stacking", "metrics_based"):
            self.meta_model_ = self._new_logistic().fit(self._meta_features(Ps), y)
        elif v == "statistical_meta":
            F = self._meta_features(Ps)
            lda = LDA(variant="shrinkage", random_state=self.random_state).fit(F, y)
            k = int(max(C, min(2 * C, n // 5)))
            km = KMeans(k, variant="better_init", random_state=self.random_state).fit(F)
            yi = np.searchsorted(self.classes_, y)
            post = np.ones((k, C))
            np.add.at(post, (km.labels_, yi), 1.0)
            post /= post.sum(1, keepdims=True)
            lr = self._new_logistic().fit(F, y)
            self.meta_model_ = {"lda": lda, "kmeans": km, "cluster_posterior": post, "logistic": lr}
        elif v == "calibrated_stack":
            F = self._meta_features(Ps)
            inner = stratified_folds(y, min(self.n_folds, 3), self.random_state + 1)
            logits = np.zeros((n, C))
            for f in np.unique(inner):
                tr, va = inner != f, inner == f
                if len(np.unique(y[tr])) < C:
                    raise ValueError("calibration fold lost a class; lower n_folds")
                logits[va] = self._new_logistic().fit(F[tr], y[tr]).decision_function(F[va])
            yi = np.searchsorted(self.classes_, y)

            def nll(logt):
                P = softmax(logits / np.exp(logt))
                return -np.mean(np.log(np.clip(P[np.arange(n), yi], 1e-12, None)))

            self.temperature_ = float(np.exp(golden_min(nll, -3.0, 3.0)))
            self.meta_model_ = self._new_logistic().fit(F, y)
        self.is_fitted_ = True
        return self

    # ------------------------------------------------------------ inference
    def _base_probas(self, X):
        return [_aligned_proba(e, X, self.classes_, self.classes_) for _, e in self.fitted_base_]

    def predict_proba(self, X):
        check_fitted(self)
        X = check_X(X, n_features=self.n_features_in_)
        Ps = self._base_probas(X)
        v = self.meta_variant
        if v == "performance_aware":
            return np.tensordot(self.weights_, np.array(Ps), axes=1)
        F = self._meta_features(Ps)
        if v in ("oof_stacking", "metrics_based"):
            return self.meta_model_.predict_proba(F)
        if v == "calibrated_stack":
            return softmax(self.meta_model_.decision_function(F) / self.temperature_)
        mm = self.meta_model_
        p_cluster = mm["cluster_posterior"][mm["kmeans"].predict(F)]
        P = (mm["lda"].predict_proba(F) + p_cluster + mm["logistic"].predict_proba(F)) / 3.0
        return P

    def predict(self, X):
        check_fitted(self)
        return self.classes_[np.argmax(self.predict_proba(X), axis=1)]

    def evaluate(self, X, y):
        X, y = check_Xy(X, y, min_samples=1)
        return classification_metrics(y, self.predict(X), self.predict_proba(X), classes=self.classes_)
